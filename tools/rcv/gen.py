from .vectors import make_rows, parse_ports

ROOT = Path(os.environ.get("RCV_ROOT") or Path(__file__).resolve().parents[2])
PKG_DIR = ROOT / "packages"
TASKS = Path(__file__).with_name("program_tasks")
PUBLIC_SEED = 1

PARTS = {
    "wiring": "Splitter, Tunnel, Const, Ground, VDD, Text, In, Out, Clock",
    "gates": "And, Or, Not, NAnd, NOr, XOr, XNOr + wiring parts",
    "gates+mux": "gates + Multiplexer, Demultiplexer, Decoder, PriorityEncoder",
    "gates+ff": "gates + D_FF, JK_FF, T_FF, RS_FF",
    "gates+mux+ff": "gates + multiplexer/decoder parts + flip-flops",
    "gates+mux+ff+arith": "all of the above + Add, Sub, Comparator, Neg",
    "gates+mux+rom": "gates + multiplexer/decoder parts + ROM",
}

INSTR_TRACE = ["LUI", "AUIPC", "JAL", "JALR", "BEQ (taken)", "BNE (not taken)", "BLT", "BGE",
               "BLTU", "BGEU", "LB", "LBU", "LW", "SB", "SW", "ADDI", "SLTI", "SLTIU", "XORI",
               "ORI", "ANDI", "SLLI", "SRLI", "SRAI", "ADD", "SUB", "SLL", "SLT", "SLTU", "XOR",
               "SRL", "SRA", "OR", "AND", "CSRRW", "ECALL (trap)", "MRET", "timer interrupt",
               "LW from an I/O device", "SW to the terminal", "a DMA-stolen cycle"]

UNIT_NAMES = {1: "Digital logic circuits", 2: "Digital components", 3: "Data representation",
              4: "Basic computer organisation", 5: "Processors", 6: "Memory and I/O"}


def pid(p):
    return f"P{p['id']:02d}"


def folder(p):
    return PKG_DIR / f"{pid(p)}-{p['slug']}"


def module_name(p):
    return f"p{p['id']:02d}_{p['slug']}"


# ------------------------------------------------------------------ Verilog
def v_decl(d, n, w):
    rng = f"[{w - 1}:0] " if w > 1 else ""
    return f"    {'input ' if d == 'in' else 'output'} wire {rng}{n}"


def verilog_stub(p):
    ports = parse_ports(p["ports"])
    lines = [f"// {pid(p)} {p['title']}",
             "// Keep the module name and the port list exactly as they are.",
             "// You may change 'output wire' to 'output reg' if you assign an output in an always block.",
             "// Delete the placeholder assigns and write your design.",
             f"module {module_name(p)} " + ("#(parameter INIT_FILE = \"boot.hex\") " if p["id"] == 30 else "") + "(",
             ",\n".join(v_decl(*x) for x in ports),
             ");", ""]
    for d, n, w in ports:
        if d == "out":
            lines.append(f"    assign {n} = {w}'d0;   // placeholder")
    lines += ["", "endmodule", ""]
    return "\n".join(lines)


def vlit(v, w):
    if v is None:
        return None
    return f"{w}'h{v:x}"


def verilog_tb(p, rows):
    ports = parse_ports(p["ports"])
    ins = [x for x in ports if x[0] == "in"]
    outs = [x for x in ports if x[0] == "out"]
    L = ["// generated by tools/rcv/gen.py - do not edit", "`timescale 1ns/1ps", f"module tb_{module_name(p)};"]
    for d, n, w in ins:
        L.append(f"    reg {f'[{w-1}:0] ' if w > 1 else ''}{n}{' = 0' if n == 'clk' else ''};   // starts unknown")
    for d, n, w in outs:
        L.append(f"    wire {f'[{w-1}:0] ' if w > 1 else ''}{n};")
    L.append("    integer errors = 0, checks = 0;")
    L.append(f"    {module_name(p)} dut (" + ", ".join(f".{n}({n})" for _, n, _ in ports) + ");")
    L.append("    initial begin")
    L.append('        $display("test %s", "' + module_name(p) + '");')
    for k, (i, o) in enumerate(rows.rows):
        sets = " ".join(f"{n} = {vlit(i[n], w)};" for _, n, w in ins if n != "clk")
        L.append(f"        {sets}")
        L.append("        #1 clk = 1; #1 clk = 0; #1;" if rows.clocked else "        #1;")
        for _, n, w in outs:
            ev = o.get(n)
            if ev is None:
                continue
            L.append(f"        checks = checks + 1; if ({n} !== {vlit(ev, w)}) begin errors = errors + 1; "
                     f"if (errors <= 20) $display(\"row {k + 1}: {n} = %h, expected %h\", {n}, {vlit(ev, w)}); end")
    L.append('        $display("RESULT %s %0d/%0d checks passed", errors == 0 ? "PASS" : "FAIL", checks - errors, checks);')
    L.append("        $finish;")
    L.append("    end")
    L.append("endmodule")
    return "\n".join(L) + "\n"


def boot_rom_tb(p):
    words = [(k * 0x01010101 + 0x10203040 * (k & 1)) & 0xFFFFFFFF for k in range(spec.ROM_WORDS)]
    hexfile = "".join(f"{w:08x}\n" for w in words)
    L = ["// generated - do not edit", "`timescale 1ns/1ps", "module tb_p30_boot_rom;",
         "    reg [13:0] iaddr = 0, daddr = 0;", "    wire [31:0] idata, ddata;",
         "    integer errors = 0, checks = 0;",
         '    p30_boot_rom #(.INIT_FILE("tests/boot_test.hex")) dut (.iaddr(iaddr), .daddr(daddr), .idata(idata), .ddata(ddata));',
         "    initial begin"]
    import random
    rng = random.Random(30)
    for k in range(120):
        a, b = rng.randrange(spec.ROM_WORDS), rng.randrange(spec.ROM_WORDS)
        L.append(f"        iaddr = 14'd{a}; daddr = 14'd{b}; #1;")
        for n, x in (("idata", a), ("ddata", b)):
            L.append(f"        checks = checks + 1; if ({n} !== 32'h{words[x]:08x}) begin errors = errors + 1; "
                     f"if (errors <= 20) $display(\"{n} at %0d = %h, expected %h\", {'iaddr' if n == 'idata' else 'daddr'}, {n}, 32'h{words[x]:08x}); end")
    L += ['        $display("RESULT %s %0d/%0d checks passed", errors == 0 ? "PASS" : "FAIL", checks - errors, checks);',
          "        $finish;", "    end", "endmodule"]
    return "\n".join(L) + "\n", hexfile


# ------------------------------------------------------------------ Digital
def dig_value(v):
    return "X" if v is None else str(v)


def dig_testdata(rows):
    ins = [n for _, n, _ in rows.ins]
    outs = [n for _, n, _ in rows.outs]
    lines = [" ".join(ins + outs)]
    for i, o in rows.rows:
        lines.append(" ".join(str(i[n]) for n in ins) + " " + " ".join(dig_value(o.get(n)) for n in outs))
    return "\n".join(lines)


def dig_element(name, attrs, x, y):
    a = "".join(f"<entry><string>{k}</string>{v}</entry>" for k, v in attrs)
    return f"    <visualElement><elementName>{name}</elementName><elementAttributes>{a}</elementAttributes><pos x=\"{x}\" y=\"{y}\"/></visualElement>"


def s(v):
    return f"<string>{escape(v)}</string>"


def testcase_element(label, data, x, y):
    return dig_element("Testcase", [("Label", s(label)),
                                    ("Testdata", f"<testData><dataString>{escape(data)}</dataString></testData>")], x, y)


def digital_stub(p, testdata):
    ports = parse_ports(p["dig"]["ports"])
    ins = [x for x in ports if x[0] == "in"]
    outs = [x for x in ports if x[0] == "out"]
    els = []
    for k, (_, n, w) in enumerate(ins):
        if n == "clk":
            els.append(dig_element("Clock", [("Label", s(n)), ("Frequency", "<int>1</int>")], 100, 100 + 60 * k))
        else:
            els.append(dig_element("In", [("Label", s(n)), ("Bits", f"<int>{w}</int>")], 100, 100 + 60 * k))
    for k, (_, n, w) in enumerate(outs):
        els.append(dig_element("Out", [("Label", s(n)), ("Bits", f"<int>{w}</int>")], 900, 100 + 60 * k))
    note = f"{pid(p)} {p['title']} - Digital task\n{p['dig']['note']}\nAllowed parts: {PARTS[p['dig']['parts']]}\n" \
           "Do not rename, move or delete the input and output pins."
    els.append(dig_element("Text", [("Description", s(note))], 100, 40))
    y = 140 + 60 * max(len(ins), len(outs))
    els.append(testcase_element("public tests", testdata, 100, y))
    return ('<?xml version="1.0" encoding="utf-8"?>\n<circuit>\n  <version>1</version>\n  <attributes/>\n'
            "  <visualElements>\n" + "\n".join(els) + "\n  </visualElements>\n  <wires/>\n"
            "  <measurementOrdering/>\n</circuit>\n")


def digital_tests(testdata, label="public tests"):
    return ('<?xml version="1.0" encoding="utf-8"?>\n<circuit>\n  <version>1</version>\n  <attributes/>\n'
            "  <visualElements>\n" + testcase_element(label, testdata, 0, 0) +
            "\n  </visualElements>\n  <wires/>\n  <measurementOrdering/>\n</circuit>\n")


def bootrom_dig_tests():
    res = assemble_files([ROOT / "sw/lib/crt0.s", ROOT / "sw/lib/rcv_lib.s"])
    words = [res["rom"].get(4 * k, 0) for k in range(16)]
    lines = ["addr data"] + [f"{k} {w}" for k, w in enumerate(words)]
    return "\n".join(lines), words


